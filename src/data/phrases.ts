function build(scene: PhraseScene, prefix: string, rows: Row[]): Phrase[] {
  return rows.map(([en, ja, note], i) => ({
    id: `${prefix}${String(i + 1).padStart(3, '0')}`,
    en,
    ja,
    scene,
    ...(note ? { note } : {}),
  }))
}

